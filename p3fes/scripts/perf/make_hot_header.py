#!/usr/bin/env python3
"""Write ps2xRuntime/include/ps2_hot_functions.h from macOS `sample` files of the bench.

Every recompiled function seen in a sample gets __attribute__((hot)), which makes GCC place it in .text.hot;
the Vita linker script keeps .text.hot together, so the code a frame executes shares instruction-cache lines and
TLB pages instead of being spread over the 27 MB of generated code.
usage: make_hot_header.py SAMPLE [SAMPLE ...]   (run from the repository root)"""
import re, sys, collections
counts = collections.Counter()
for path in sys.argv[1:]:
    for name in re.findall(r"([A-Za-z_][A-Za-z_0-9]*_0x[0-9a-f]{6})\(", open(path, errors="replace").read()):
        counts[name] += 1
declared = set(re.findall(r"^void (\w+)\(", open("ps2xRuntime/include/ps2_recompiled_functions.h").read(), re.M))
hot = [n for n, _ in counts.most_common() if n in declared]
with open("ps2xRuntime/include/ps2_hot_functions.h", "w") as out:
    out.write("// Generated by p3fes/scripts/perf/make_hot_header.py; do not edit.\n#pragma once\n#include <cstdint>\n"
              "struct R5900Context;\nclass PS2Runtime;\n")
    for n in hot:
        out.write(f"__attribute__((hot)) void {n}(uint8_t* rdram, R5900Context* ctx, PS2Runtime *runtime);\n")
print(len(hot), "hot functions")
