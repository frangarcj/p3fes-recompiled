#!/usr/bin/env python3
"""Select leaf generated functions from ps2xRuntime/src/runner and emit test TUs.

Leaf = no calls, no guest-branch dispatch, no syscalls/stubs, no explicit runtime->Load/Store.
Deviations from a purely textual filter (see README in run.sh header):
  * text inside the `#if defined(PS2X_STRICT_RETURN_DIAGNOSTICS) ... #else` arm is not compiled
    by default, so dispatchGuestBranch there is ignored;
  * `runtime->eeCheckpointDue(` (backward-branch checkpoints) is allowed: the test supplies a fake
    runtime object with a finite budget that aborts when exhausted;
  * `switch (ctx->pc)` is allowed: the test enters with ctx->pc = 0 (default arm = normal entry).
Use --strict to apply the literal filter.
"""
import argparse, os, re, sys, collections

BAD = [r'dispatchGuestBranch', r'PS2_CALL_DIRECT', r'ps2_syscalls::', r'ps2_stubs::',
       r'\(rdram, ctx, runtime\);']
BAD_STRICT = [r'runtime->', r'eeCheckpointDue', r'switch \(ctx->pc\)']
RUNTIME_OK = re.compile(r'runtime->(?!eeCheckpointDue\()')

def active_text(src):
    out, skip = [], False
    for line in src.split('\n'):
        s = line.strip()
        if s.startswith('#if') and 'PS2X_STRICT_RETURN_DIAGNOSTICS' in s and '!' not in s:
            skip = True; continue
        if skip and s.startswith('#else'):
            skip = False; continue
        if skip and s.startswith('#endif'):
            skip = False; continue
        if not skip:
            out.append(line)
    return '\n'.join(out)

FEATURES = {
  'lwl_lwr': r'\b(lwl|lwr|ldl|ldr|swl|swr|sdl|sdr)\b',
  'ld': r'\bld\s', 'sd': r'\bsd\s', 'lq': r'\blq\s', 'sq': r'\bsq\s',
  'lb': r'\blbu?\s', 'sb': r'\bsb\s', 'lh': r'\blhu?\s', 'sh': r'\bsh\s',
  'lw': r'\blwu?\s', 'sw': r'\bsw\s', 'fpu_mem': r'\b(lwc1|swc1)\b',
  'mmi': r'PS2_P[A-Z0-9]+\(', 'fpu': r'\b(add\.s|mul\.s|sub\.s|div\.s|cvt\.|c\.[a-z]+\.s)', 'loop': r'eeCheckpointDue',
}

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--runner', required=True)
    ap.add_argument('--out', required=True)
    ap.add_argument('--chunk', type=int, default=40)
    ap.add_argument('--max', type=int, default=0, help='0 = all candidates')
    ap.add_argument('--strict', action='store_true')
    ap.add_argument('--maxlines', type=int, default=3000)
    a = ap.parse_args()

    cands = []
    for fn in sorted(os.listdir(a.runner)):
        if not fn.endswith('.cpp'): continue
        p = os.path.join(a.runner, fn)
        src = open(p, errors='replace').read()
        if src.count('\n') > a.maxlines: continue
        t = active_text(src)
        if any(re.search(b, t) for b in BAD): continue
        if a.strict:
            if any(re.search(b, t) for b in BAD_STRICT): continue
        elif RUNTIME_OK.search(t): continue
        m = re.search(r'^void (\w+)\(uint8_t\* rdram, R5900Context\* ctx, PS2Runtime \*runtime\)', t, re.M)
        if not m: continue
        feats = {k for k, r in FEATURES.items() if re.search(r, t)}
        cands.append((fn, m.group(1), feats, t.count('\n')))
    print(f'candidates: {len(cands)}', file=sys.stderr)

    if a.max and len(cands) > a.max:
        # greedy coverage: rarest features first, then fill with small functions evenly
        freq = collections.Counter(f for c in cands for f in c[2])
        chosen, seen = [], collections.Counter()
        for feat, _ in sorted(freq.items(), key=lambda kv: kv[1]):
            for c in cands:
                if feat in c[2] and c not in chosen and seen[feat] < max(8, a.max // 25):
                    chosen.append(c)
                    for f in c[2]: seen[f] += 1
        rest = [c for c in cands if c not in chosen]
        step = max(1, len(rest) // max(1, a.max - len(chosen)))
        chosen += rest[::step][:max(0, a.max - len(chosen))]
        cands = sorted(chosen)

    os.makedirs(a.out, exist_ok=True)
    for f in os.listdir(a.out):
        if f.startswith('chunk_') or f == 'manifest.txt':
            os.remove(os.path.join(a.out, f))
    chunks = [cands[i:i + a.chunk] for i in range(0, len(cands), a.chunk)]
    for ci, ch in enumerate(chunks):
        with open(os.path.join(a.out, f'chunk_{ci}.cpp'), 'w') as o:
            o.write('// generated by select_leaves.py\n#include "harness.h"\n')
            for fn, name, _, _ in ch:
                o.write(f'#include "{os.path.join(os.path.abspath(a.runner), fn)}"\n')
            o.write(f'extern const FuncEntry g_chunk_{ci}[];\nextern const int g_chunk_{ci}_n;\n')
            o.write(f'const FuncEntry g_chunk_{ci}[] = {{\n')
            for fn, name, _, _ in ch:
                o.write(f'    {{"{name}", &{name}}},\n')
            o.write(f'}};\nconst int g_chunk_{ci}_n = {len(ch)};\n')
    with open(os.path.join(a.out, 'chunk_table.inc'), 'w') as o:
        for ci in range(len(chunks)):
            o.write(f'extern const FuncEntry g_chunk_{ci}[]; extern const int g_chunk_{ci}_n;\n')
        o.write('static const ChunkRef g_chunks[] = {\n')
        for ci in range(len(chunks)):
            o.write(f'    {{g_chunk_{ci}, &g_chunk_{ci}_n}},\n')
        o.write('};\n')
    with open(os.path.join(a.out, 'manifest.txt'), 'w') as o:
        for fn, name, feats, n in cands:
            o.write(f'{name}\t{fn}\t{n}\t{",".join(sorted(feats))}\n')
    print(f'selected {len(cands)} in {len(chunks)} chunks', file=sys.stderr)
    cnt = collections.Counter(f for c in cands for f in c[2])
    print(dict(cnt), file=sys.stderr)

main()
