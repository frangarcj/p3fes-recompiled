export function detectLang() {
  try {
    const saved = localStorage.getItem('p3fes-lang');
    if (saved === 'en' || saved === 'es') return saved;
  } catch { /* storage may be blocked */ }
  const nav = (typeof navigator !== 'undefined' && (navigator.language || '')) || 'en';
  return nav.toLowerCase().startsWith('es') ? 'es' : 'en';
}

export function saveLang(l) { try { localStorage.setItem('p3fes-lang', l); } catch { /* ignore */ } }

export function format(str, vars = {}) {
  return String(str).replace(/\{(\w+)\}/g, (_, k) => (k in vars ? vars[k] : `{${k}}`));
}
